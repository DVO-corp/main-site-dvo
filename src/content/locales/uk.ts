/**
 * Loose structural constraint so `as const` keeps literal types for `uk`
 * while still catching obvious typos. The precise contract for the other
 * locales is `Dictionary`, derived below.
 */
type DictionaryShape = Record<string, unknown>;

/** Recursively widens literal types so translations are plain strings. */
export type Widen<T> = T extends string
  ? string
  : T extends number
    ? number
    : T extends boolean
      ? boolean
      : T extends readonly (infer U)[]
        ? Widen<U>[]
        : T extends object
          ? { -readonly [K in keyof T]: Widen<T[K]> }
          : T;

